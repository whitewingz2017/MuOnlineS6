using System.Text;
using System.Text.Json;
using Microsoft.Extensions.Logging.Abstractions;
using MUnique.OpenMU.AttributeSystem;
using MUnique.OpenMU.DataModel;
using MUnique.OpenMU.DataModel.Configuration;
using MUnique.OpenMU.DataModel.Configuration.Items;
using MUnique.OpenMU.DataModel.Entities;
using MUnique.OpenMU.GameLogic;
using MUnique.OpenMU.GameLogic.Attributes;
using MUnique.OpenMU.Persistence.InMemory;
using MUnique.OpenMU.Persistence.Initialization.VersionSeasonSix;

var root = Path.GetFullPath(args[0]);
var provider = new InMemoryPersistenceContextProvider();
await new DataInitialization(provider, NullLoggerFactory.Instance).CreateInitialDataAsync(1, true);
using var context = provider.CreateNewContext();
var config = (await context.GetAsync<GameConfiguration>()).First();
AttributeDefinition[] direct = [Stats.Level, Stats.TotalStrength, Stats.TotalAgility, Stats.TotalVitality, Stats.TotalEnergy, Stats.TotalLeadership];
AttributeDefinition?[] mapped = [null, Stats.TotalStrengthRequirementValue, Stats.TotalAgilityRequirementValue, Stats.TotalVitalityRequirementValue, Stats.TotalEnergyRequirementValue, Stats.TotalLeadershipRequirementValue];
var source = new StringBuilder("// Generated by tools/ExportServerItemRequirements from OpenMU Season Six initialization.\nnamespace Client.Main.Core.Utilities;\ninternal sealed record ServerItemRequirementProfile(int DropLevel, bool Wearable, bool Book, int Mapped, int[] Values);\ninternal static class ServerItemRequirements\n{\n    internal static readonly System.Collections.Generic.Dictionary<(int, int), ServerItemRequirementProfile> Profiles = new()\n    {\n");
var cases = new List<object>();
foreach (var d in config.Items.OrderBy(x => x.Group).ThenBy(x => x.Number))
{
    var values = new int[6]; int mask = 0;
    for (int i = 0; i < 6; i++)
    {
        var r = d.Requirements.FirstOrDefault(r => r.Attribute == direct[i] || mapped[i] != null && r.Attribute == mapped[i]);
        if (r != null) { values[i] = r.MinimumValue; if (r.Attribute == mapped[i]) mask |= 1 << i; }
    }
    var item = context.CreateNew<Item>(); item.Definition = d;
    bool book = item.IsBook(out _);
    source.AppendLine($"        [({d.Group}, {d.Number})] = new({d.DropLevel}, {item.IsWearable().ToString().ToLowerInvariant()}, {book.ToString().ToLowerInvariant()}, {mask}, [{string.Join(", ", values)}]),");
    foreach (int level in new[] { 0, 1, 7, 15 })
    foreach (int variant in new[] { 0, 1, 2 })
    foreach (int optionLevel in new[] { 0, 1, 7 })
    {
        item.Level = (byte)level; item.ItemOptions.Clear(); item.ItemSetGroups.Clear();
        if (variant == 1) { var link = context.CreateNew<ItemOptionLink>(); link.ItemOption = context.CreateNew<IncreasableItemOption>(); link.ItemOption.OptionType = ItemOptionTypes.Excellent; item.ItemOptions.Add(link); }
        if (variant == 2) { var set = context.CreateNew<ItemOfItemSet>(); set.AncientSetDiscriminator = 1; item.ItemSetGroups.Add(set); }
        if (optionLevel > 0) { var link = context.CreateNew<ItemOptionLink>(); link.Level = (byte)optionLevel; link.ItemOption = context.CreateNew<IncreasableItemOption>(); link.ItemOption.OptionType = ItemOptionTypes.Option; item.ItemOptions.Add(link); }
        var result = new int[6];
        foreach (var requirement in d.Requirements)
        {
            var (attribute, value) = item.GetRequirement(requirement);
            int index = Array.FindIndex(direct, a => a == attribute);
            if (index >= 0) result[index] = value;
        }
        cases.Add(new { Group = (int)d.Group, Id = (int)d.Number, Level = level, Variant = variant, Option = optionLevel, Expected = result });
    }
}
source.AppendLine("    };\n}");
await File.WriteAllTextAsync(Path.Combine(root, "Client.Main/Core/Utilities/ServerItemRequirements.Generated.cs"), source.ToString());
await File.WriteAllTextAsync(Path.Combine(root, "tests/ItemAttributes/server-requirement-cases.json"), JsonSerializer.Serialize(cases));
Console.WriteLine($"Exported {config.Items.Count} server item profiles and {cases.Count} requirement cases.");

// Export the server's unrounded base prices and durability curves, so client
// tooltips use the same item definitions as the transactions on the server.
var buying = typeof(ItemPriceCalculator).GetMethod("CalculateBuyingPrice", System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Static)!;
var prices = new StringBuilder("// Generated from OpenMU Season Six by tools/ExportServerItemRequirements.\nnamespace Client.Main.Core.Utilities;\ninternal sealed record ServerPriceProfile(bool Stack, bool Options, bool SkillValue, long[] Prices, int[] Durability);\ninternal static class ServerItemPrices\n{\ninternal static readonly System.Collections.Generic.Dictionary<(int,int),ServerPriceProfile> Profiles = new()\n{\n");
foreach (var d in config.Items.OrderBy(x => x.Group).ThenBy(x => x.Number))
{
    var item = context.CreateNew<Item>(); item.Definition = d;
    bool ammunition = d.Group == 4 && d.Number is 7 or 15;
    item.Durability = ammunition ? d.Durability : 1;
    var bases = new List<long>(); var durability = new List<int>();
    for (int excellent = 0; excellent < 2; excellent++)
    {
        item.ItemOptions.Clear();
        if (excellent != 0)
        {
            var link = context.CreateNew<ItemOptionLink>();
            link.ItemOption = context.CreateNew<IncreasableItemOption>();
            link.ItemOption.OptionType = ItemOptionTypes.Excellent;
            item.ItemOptions.Add(link);
        }
        for (byte level = 0; level < 16; level++)
        {
            item.Level = level;
            bases.Add((long)buying.Invoke(null, [item])!);
            durability.Add(item.GetMaximumDurabilityOfOnePiece());
        }
    }
    bool stack = d.Group == 14 && d.Number <= 8 || d.Group == 4 && d.Number is 7 or 15;
    bool options = d.Value == 0 && (d.Group <= 11 && !(d.Group == 4 && d.Number is 7 or 15) || item.IsWing());
    bool skillValue = d.Skill?.Number is not (null or 66 or 223 or 224 or 225);
    prices.AppendLine($"[({d.Group},{d.Number})] = new({stack.ToString().ToLowerInvariant()},{options.ToString().ToLowerInvariant()},{skillValue.ToString().ToLowerInvariant()},[{string.Join(',', bases)}],[{string.Join(',', durability)}]),");
}
prices.AppendLine("};\n}");
await File.WriteAllTextAsync(Path.Combine(root, "Client.Main/Core/Utilities/ServerItemPrices.Generated.cs"), prices.ToString());
